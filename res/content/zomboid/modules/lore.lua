local PLACES = {}
for id, story in ipairs(lore.STORIES) do
    if story.place then
        PLACES[story.place] = id
    end
end

local HOME = {}
for id, story in ipairs(lore.STORIES) do
    if story.place == nil then
        table.insert(HOME, id)
    end
end

function lore.place_story(place)
    return PLACES[place]
end

function lore.home_story(r)
    return HOME[1 + math.floor(r * #HOME) % #HOME]
end

function lore.story_at(x, z)
    local town = require "zomboid:town"
    local place = require("zomboid:decor/aftermath").place_at(x, z) or require("zomboid:decor/parks").place_at(x, z)
    return PLACES[place] or lore.home_story(town.hash(x, z, 71))
end

function lore.read(pid, id)
    lore.current[pid] = id
    if hud and hud.get_player() == pid then
        hud.show_overlay("zomboid:note", false)
    end
end

function lore.give(pid, id)
    local invid = player.get_inventory(pid)
    local slot = inventory.find_by_item(invid, 0, 0, inventory.size(invid) - 1, 0)
    if slot == nil then
        return false
    end
    inventory.set(invid, slot, item.index("zomboid:lore_note"), 1)
    inventory.set_data(invid, slot, "story", id)
    inventory.set_description(invid, slot, lore.STORIES[id].title)
    return true
end

return lore
